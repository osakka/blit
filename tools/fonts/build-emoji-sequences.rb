#!/usr/bin/env ruby
# Derived data only. The Unicode corpus/manifest remains authoritative.
require 'json'
require 'digest'
root = File.expand_path('../..', __dir__)
Dir.chdir(root) do
  manifest = JSON.parse(File.read('assets/unicode/emoji-18.0/source.json'))
  input = File.join('assets/unicode/emoji-18.0', manifest.fetch('test_data').fetch('file'))
  raise 'corpus identity mismatch' unless Digest::SHA256.file(input).hexdigest == manifest.fetch('test_data').fetch('sha256')
  rows = File.readlines(input).filter_map { |line| (m = line.match(/^([0-9A-F ]+)\s*;/)) && m[1].split.map { |v| v.to_i(16) } }
  raise 'corpus bounds mismatch' unless rows.size == manifest.fetch('entries').values.sum && rows.map(&:size).max == manifest.fetch('max_sequence_scalars')
  trie = {cp:0, children:{}, terminal:false}
  rows.each do |scalars|
    node = trie
    scalars.each { |cp| node = (node[:children][cp] ||= {cp:cp, children:{}, terminal:false}) }
    node[:terminal] = true
  end
  queue = [trie]; index = 0; records = []
  while index < queue.size
    node = queue[index]; children = node[:children].sort.map(&:last)
    records << "    {0x#{node[:cp].to_s(16)}, #{queue.size}, #{children.size}, #{node[:terminal] ? 1 : 0}},"
    queue.concat(children); index += 1
  end
  raise 'trie index overflow' unless queue.size < 65536
  output = "/* Generated by tools/fonts/build-emoji-sequences.rb; do not edit.\n * Corpus SHA256 #{manifest.fetch('test_data').fetch('sha256')}\n */\n#ifndef BLIT_EMOJI_SEQUENCES_DATA_H\n#define BLIT_EMOJI_SEQUENCES_DATA_H\n#define BLIT_EMOJI_SEQUENCE_COUNT #{rows.size}\nstatic const BlitEmojiNode blit_emoji_nodes[] = {\n#{records.join("\n")}\n};\n#endif\n"
  path = ARGV.fetch(0, 'src/blit_emoji_sequences_data.h')
  File.binwrite(path, output)
  puts "EMOJI_TRIE nodes=#{queue.size} sequences=#{rows.size} output=#{path}"
end
