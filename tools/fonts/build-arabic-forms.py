#!/usr/bin/env python3
"""Writes src/blit_arabic_forms.h (ADR 0241): each Arabic presentation form
Hibr can send -> its form (isolated, initial, medial, final) and its letters
(lam-alef -> lam, alef), from the Unicode decomposition pinned in
assets/fonts/arabic-fonts.source.json. The spacing marks (U+FE70-FE7F,
decomposed with a space) and the long phrases U+FDFA/FDFB are left out.

    python3 tools/fonts/build-arabic-forms.py src/blit_arabic_forms.h
"""
import json
import sys
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[2]
pinned = json.loads((root / 'assets/fonts/arabic-fonts.source.json').read_text())['build']['unicode_decomposition_version']
if unicodedata.unidata_version != pinned:
    raise SystemExit(f'use a Python with Unicode {pinned} (this one has {unicodedata.unidata_version})')
FORMS = {'<isolated>': 0, '<initial>': 1, '<medial>': 2, '<final>': 3}
rows = []
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFEFD)):
    d = unicodedata.decomposition(chr(cp)).split()
    if not d or d[0] not in FORMS:
        continue
    letters = [int(x, 16) for x in d[1:]]
    if 0x20 in letters or len(letters) > 6:
        continue
    rows.append((cp, FORMS[d[0]], letters))
out = [
    f'/* Generated by tools/fonts/build-arabic-forms.py from the Unicode {pinned}',
    '   decomposition pinned in assets/fonts/arabic-fonts.source.json (ADR 0241).',
    '   Do not edit. */',
    '#ifndef BLIT_ARABIC_FORMS_H',
    '#define BLIT_ARABIC_FORMS_H',
    '',
    '/* form: 0 isolated, 1 initial, 2 medial, 3 final */',
    'typedef struct { unsigned short scalar; unsigned char form, count; unsigned short letters[6]; } BlitArabicForm;',
    '',
    'static const BlitArabicForm blit_arabic_forms[] = {',
]
for cp, form, letters in rows:
    padded = letters + [0] * (6 - len(letters))
    out.append('    {0x%04X, %d, %d, {%s}},' % (cp, form, len(letters), ', '.join('0x%04X' % x for x in padded)))
out += ['};', f'#define BLIT_ARABIC_FORM_COUNT {len(rows)}', '', '#endif', '']
Path(sys.argv[1]).write_text('\n'.join(out))
print(f'{len(rows)} forms, Unicode {pinned}')
