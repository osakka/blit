#!/usr/bin/env ruby
require 'json'
require 'digest'
root = File.expand_path('../..', __dir__)
Dir.chdir(root) do
  manifest = JSON.parse(File.read('assets/unicode/emoji-18.0/source.json'))
  data = %w[properties variations].to_h do |key|
    item = manifest.fetch(key); path = File.join('assets/unicode/emoji-18.0',item.fetch('file'))
    raise "identity mismatch: #{key}" unless Digest::SHA256.file(path).hexdigest == item.fetch('sha256')
    [key, File.readlines(path)]
  end
  defaults = data['properties'].filter_map do |line|
    m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Emoji_Presentation\s*#/)
    m && [m[1].to_i(16), (m[2] || m[1]).to_i(16)]
  end
  bases = data['variations'].filter_map { |l| (m = l.match(/^([0-9A-F]+) FE0E\s*;/)) && m[1].to_i(16) }
  emoji_bases = data['variations'].filter_map { |l| (m = l.match(/^([0-9A-F]+) FE0F\s*;/)) && m[1].to_i(16) }
  raise 'variation/count drift' unless bases == bases.sort.uniq && bases == emoji_bases && bases.size == manifest.dig('variations','bases') && defaults.sum { |a,b| b-a+1 } == manifest.dig('properties','default_emoji_scalars')
  raise 'unordered/overlapping presentation ranges' unless defaults.all? { |a,b| a <= b && b <= 0x10ffff } && defaults.each_cons(2).all? { |left,right| left[1] < right[0] }
  out = "/* Generated by tools/fonts/build-emoji-presentation.rb; source hashes in\n * assets/unicode/emoji-18.0/source.json. Do not edit. */\n#ifndef BLIT_EMOJI_PRESENTATION_H\n#define BLIT_EMOJI_PRESENTATION_H\n#include <stdint.h>\n#include <stddef.h>\ntypedef struct { uint32_t first, last; } BlitEmojiPresentationRange;\n"
  {'default'=>defaults, 'variation'=>bases.map { |cp| [cp,cp] }}.each do |name, ranges|
    out << "static const BlitEmojiPresentationRange blit_emoji_#{name}_ranges[] = {\n"
    ranges.each { |a,b| out << "    {0x#{a.to_s(16)}, 0x#{b.to_s(16)}},\n" }
    out << "};\n"
  end
  out << <<~C
    static int blit_emoji_presentation_contains(const BlitEmojiPresentationRange *ranges, size_t count, uint32_t cp)
    {
        size_t low = 0, high = count;
        while (low < high) {
            size_t mid = low + (high - low) / 2;
            if (cp < ranges[mid].first) high = mid;
            else if (cp > ranges[mid].last) low = mid + 1;
            else return 1;
        }
        return 0;
    }
    static int blit_emoji_default(uint32_t cp)
    { return blit_emoji_presentation_contains(blit_emoji_default_ranges, sizeof(blit_emoji_default_ranges)/sizeof(*blit_emoji_default_ranges), cp); }
    static int blit_emoji_variation(uint32_t cp)
    { return blit_emoji_presentation_contains(blit_emoji_variation_ranges, sizeof(blit_emoji_variation_ranges)/sizeof(*blit_emoji_variation_ranges), cp); }
    #endif
  C
  File.binwrite(ARGV.fetch(0,'src/blit_emoji_presentation.h'),out)
  puts "EMOJI_PRESENTATION_DATA_PASS bases=#{bases.size} default_emoji=#{defaults.sum { |a,b| b-a+1 }}"
end
